/**
 * Inlines the CHANGELOG section of the current package version into the README
 * block between the `<!-- changelog:start -->` / `<!-- changelog:end -->`
 * markers.
 *
 * Run by `release.yml` right before `npm publish`, so the npm package page shows
 * the release notes instead of only a link. The repository keeps the placeholder
 * text inside the markers - CHANGELOG.md stays the single source of truth.
 *
 * Usage:
 *   node scripts/build-npm-readme.mjs          # rewrite README.md
 *   node scripts/build-npm-readme.mjs --check  # only validate (ci.yml)
 */

import { readFileSync, writeFileSync } from "node:fs";
import { changelogDate, changelogSection } from "./changelog-section.mjs";

const README = "README.md";
const CHANGELOG = "CHANGELOG.md";
const PACKAGE = "package.json";
const START = "<!-- changelog:start -->";
const END = "<!-- changelog:end -->";

function fail(message) {
  console.error(`::error::${message}`);
  process.exit(1);
}

const version = JSON.parse(readFileSync(PACKAGE, "utf8")).version;
const changelog = readFileSync(CHANGELOG, "utf8");
const readme = readFileSync(README, "utf8");

const section = changelogSection(changelog, version);
if (!section) fail(`${CHANGELOG} has no ## [${version}] section`);
const date = changelogDate(changelog, version);

const start = readme.indexOf(START);
const end = readme.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  fail(`${README} needs the ${START} / ${END} markers around the changelog block`);
}
if (readme.indexOf(START, start + 1) !== -1 || readme.indexOf(END, end + 1) !== -1) {
  fail(`${README} has duplicate ${START}/${END} markers`);
}

if (process.argv.includes("--check")) {
  console.log(`${README} changelog block can be generated for ${version}.`);
  process.exit(0);
}

const generated = [
  START,
  "<!-- Generated by scripts/build-npm-readme.mjs at release time; source of truth: CHANGELOG.md -->",
  `**${version}${date ? ` - ${date}` : ""}**`,
  "",
  section,
  "",
  "Full history and all versions: [CHANGELOG.md](./CHANGELOG.md)",
  END,
].join("\n");

writeFileSync(README, readme.slice(0, start) + generated + readme.slice(end + END.length), "utf8");
console.log(`Inlined the ${version} changelog section into ${README}.`);
